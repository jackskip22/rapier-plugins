#!/usr/bin/env python3
"""Regenerate Word's static Geist sfnts from the shipped WOFF2 owners.

Requires fontTools 4.61.1 and Brotli. Node's built-in Brotli is sufficient where
the Python extension is absent. This is asset preparation, never export work.
"""
import base64
import hashlib
import io
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import types

try:
    import brotli
except ImportError:
    node = os.environ.get('NODE', 'node')
    def decompress(data):
        return subprocess.run([node, '-e',
            'const fs=require("node:fs"),z=require("node:zlib");'
            'process.stdout.write(z.brotliDecompressSync(fs.readFileSync(0)))'],
            input=data, stdout=subprocess.PIPE, check=True).stdout
    sys.modules['brotli'] = types.SimpleNamespace(decompress=decompress)

import fontTools
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

if fontTools.__version__ != '4.61.1':
    raise RuntimeError('The recorded Word font derivation uses fontTools 4.61.1')

root = Path(__file__).resolve().parents[1]
folder = root / 'shell/fonts'
provenance = json.loads((folder / 'PROVENANCE.json').read_text())
notice = re.search(r'Geist · Geist Mono</span>[\s\S]*?<pre class="license-text">([\s\S]*?)</pre>',
                  (root / 'editor/ui.html').read_text()).group(1)
rows = [
    ('Geist', 'Geist', 400, 'Regular'),
    ('Geist', 'Geist', 560, 'Bold'),
    ('Geist Mono', 'Geist Mono', 400, 'Regular'),
    ('Geist Mono', 'Geist Mono', 560, 'Bold'),
]
assets = []
font_data = bytearray()
for source_family, family, weight, style in rows:
    source = provenance['fonts'][source_family]['instanced']
    data = (folder / source['file']).read_bytes()
    if hashlib.sha256(data).hexdigest() != source['sha256']:
        raise RuntimeError('The licensed font source changed: ' + source['file'])
    font = TTFont(io.BytesIO(data), recalcTimestamp=False)
    font = instantiateVariableFont(font, {'wght': weight}, inplace=True)
    font.flavor = None
    font['OS/2'].usWeightClass = weight
    # Native Word selects two styles by family. Its bold slot holds the exact
    # reference CSS weight560, including default headings and table headers.
    bold = style == 'Bold'
    font['OS/2'].fsSelection = (font['OS/2'].fsSelection & ~96) | (32 if bold else 64)
    font['head'].macStyle = (font['head'].macStyle & ~1) | int(bold)
    stem = family.replace(' ', '') + '-' + style
    for name_id, value in [(1, family), (2, style), (3, stem + ';static-wght' + str(weight)),
                           (4, family + ' ' + style), (6, stem), (13, notice),
                           (14, 'http://scripts.sil.org/OFL'), (16, family), (17, style)]:
        font['name'].setName(value, name_id, 3, 1, 0x409)
    output = io.BytesIO()
    font.save(output)
    sfnt = output.getvalue()
    digest = hashlib.sha256(sfnt).hexdigest()
    assets.append({'family': family, 'style': style, 'weight': weight,
        'bytes': len(sfnt), 'sha256': digest,
        'offset': len(font_data)})
    font_data.extend(sfnt)

# One lossless stream shares the identical tables across the four static faces.
# The editor already carries this bounded Brotli decoder for custom WOFF2 fonts.
# Keep the original sfnt bytes and metadata; expand only on first Word/PDF use.
packed = subprocess.run([os.environ.get('NODE', 'node'), '-e',
    'const fs=require("node:fs"),z=require("node:zlib"),c=z.constants;'
    'const bytes=fs.readFileSync(0),packed=z.brotliCompressSync(bytes,{params:{'
    '[c.BROTLI_PARAM_QUALITY]:11,[c.BROTLI_PARAM_MODE]:c.BROTLI_MODE_FONT,'
    '[c.BROTLI_PARAM_LGWIN]:22}});'
    'if(!z.brotliDecompressSync(packed).equals(bytes))throw Error("Font packing changed bytes");'
    'process.stdout.write(packed);'], input=font_data, stdout=subprocess.PIPE, check=True).stdout

(folder / 'docx-fonts.mjs').write_text(
    '// Geist font software: original copyright notices retained in each sfnt.\n'
    '// SIL Open Font License 1.1; license retained in each sfnt name table and editor/ui.html.\n'
    '// Generated by tools/build-docx-fonts.py. See PROVENANCE.json; do not hand-edit.\n'
    'import {decodeBrotli} from "../../draw/font-brotli.mjs";\n'
    'const PACKED = ' + json.dumps(base64.b64encode(packed).decode('ascii')) + ';\n'
    'let decoded;\n'
    'function fontView(offset, length) {\n'
    '  decoded ||= decodeBrotli(Uint8Array.from(atob(PACKED), c => c.charCodeAt(0)), ' + str(len(font_data)) + ');\n'
    '  return decoded.subarray(offset, offset + length);\n'
    '}\n'
    'function fontData(offset, length) {\n'
    '  const bytes = fontView(offset, length);\n'
    '  let binary = "";\n'
    '  for (let at = 0; at < bytes.length; at += 8192)\n'
    '    binary += String.fromCharCode(...bytes.subarray(at, at + 8192));\n'
    '  return btoa(binary);\n'
    '}\n'
    'export const DOCX_FONTS = Object.freeze(' + json.dumps(assets, separators=(',', ':')) + '.map(({offset, ...font}) => {\n'
    '  let data;\n'
    '  return Object.freeze({...font, get data() { return data ??= fontData(offset, font.bytes); },\n'
    '    read() { return fontView(offset, font.bytes).slice(); }});\n'
    '}));\n')
provenance['word'] = {
    'generator': 'tools/build-docx-fonts.py', 'fonttools': fontTools.__version__,
    'source': 'the instanced WOFF2 files above; no glyphs subsetted or redrawn',
    'instancing': 'static wght400,560 sfnt; recalcTimestamp=False; native regular/bold family names; original copyright retained; full OFL license from editor/ui.html in name13',
    'packing': 'one Brotli stream (Node, quality11, font mode, lgwin22); exact sfnt bytes expanded lazily by draw/font-brotli.mjs; immutable faces expose owned binary reads and synchronous base64 data',
    'fonts': [{key: value for key, value in asset.items() if key != 'offset'} for asset in assets],
}
(folder / 'PROVENANCE.json').write_text(json.dumps(provenance, indent=2) + '\n')
print(json.dumps({'fonts': len(assets), 'sfntBytes': sum(asset['bytes'] for asset in assets)}))
